const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const WebSocket = require('ws');
const { once } = require('node:events');
const { start } = require('../esportra-valorant-hud/server/server');
const OutputRegistry = require('../src/output-registry');

test('stable output follows a new room on the existing socket and reports actual rendering', async t => {
  const root = path.resolve(__dirname, '../esportra-valorant-hud');
  const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'air-output-alias-'));
  let outputs = [], match = 'FINAL_A';
  const registry = new OutputRegistry({ config: { get: () => outputs, set: (_, value) => { outputs = value; } }, hudRoot: root, port: 5300, currentMatch: () => match });
  const output = registry.add({ name: 'In game', overlay: 'ingame' });
  const fixed = registry.add({ name: 'Pinned', overlay: 'scoreboard', matchCode: 'FIXED', followMatch: false });
  const server = await start({ root, dataDir, port: 0, key: 'fixture', resolveOutput: id => registry.resolve(id) });
  t.after(() => { server.stop(); fs.rmSync(dataDir, { recursive: true, force: true }); });
  const url = `http://127.0.0.1:${server.port}`;
  const html = await (await fetch(url + '/o/' + output.id)).text();
  assert.match(html, /<base href="\/overlays\/">/);
  assert.equal((await fetch(url + '/o/not-valid')).status, 404);
  const socket = new WebSocket(`ws://127.0.0.1:${server.port}/ws?output=${output.id}&role=overlay`);
  const initial = once(socket, 'message'); await once(socket, 'open');
  assert.equal(JSON.parse((await initial)[0]).type, 'snapshot');
  socket.send(JSON.stringify({ type: 'rendered', v: 0 }));
  const deadline = Date.now() + 2000;
  while (!server.getOutputHealth(output.id).lastFrameAt && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 10));
  assert.equal(server.getOutputHealth(output.id).connectionCount, 1);
  assert.ok(server.getOutputHealth(output.id).lastFrameAt);
  const before = registry.list()[0].url; match = 'FINAL_B';
  await fetch(url + '/api/FINAL_B', { method: 'PATCH', headers: { 'X-Esportra-Key': 'fixture', 'Content-Type': 'application/json' }, body: JSON.stringify({ event: { name: 'Second match' } }) });
  const moved = once(socket, 'message'); server.notifyOutputsChanged();
  assert.equal(JSON.parse((await moved)[0]).state.event.name, 'Second match');
  assert.equal(registry.list()[0].url, before); assert.equal(registry.resolve(fixed.id).matchCode, 'FIXED');
  assert.equal(server.getOutputHealth(output.id).lastFrameAt, null);
  const closed = once(socket, 'close'); registry.remove(output.id); server.notifyOutputsChanged(); await closed;
  assert.equal(server.getOutputHealth(output.id).connectionCount, 0);
});
